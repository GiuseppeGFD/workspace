print("A continuación identificaremos un cuadrado o rectángulo")
print("========================================================")
altura = float(input("Indica la altura: "))
anchura = float(input("Indica la anchura: "))
print("========================================================")
if altura == anchura:
    print(f"Como la altura ({altura}) y la anchura ({anchura}) son iguales")
    print(f".         ¡¡¡Significa que la figura es cuadrada!!!")
else:
    print(f"Como la altura ({altura}) y la anchura ({anchura}) no son iguales")
    print(f".      ¡¡¡Significa que la figura es Rectangular!!!")

